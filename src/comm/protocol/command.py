import enum


class Command(enum.IntEnum):
    # 握手消息
    HANDSHAKE_REQ = 0x0101
    HANDSHAKE_RES = 0x0201

    # 光源稳定性检测
    CHECK_LIGHT_STABILITY = 0x0110
    CHECK_LIGHT_STABILITY_RES = 0x0210
    # 标准物质波长准确性检测
    CHECK_STANDARD_WAVE_ACCURACY = 0x0111
    CHECK_STANDARD_WAVE_ACCURACY_RES = 0x0211
    # 标准物质波长重复性检测
    CHECK_STANDARD_WAVE_REPEATABILITY = 0x0112  # 标准物质波长重复性检测
    CHECK_STANDARD_WAVE_REPEATABILITY_RES = 0x0212
    # 激光信号检查
    CHECK_LASER_STABILITY = 0x011E
    CHECK_LASER_STABILITY_RES = 0x021E
    # 停止检测
    CHECK_STOP = 0x011F

    # 采集暗噪声
    COLLECT_DARK_NOISE_REQ = 0x0120
    COLLECT_DARK_NOISE_RES = 0x0220
    # 采集背景
    COLLECT_BACKGROUND_REQ = 0x0121
    COLLECT_BACKGROUND_RES = 0x0221
    # 采集样本
    COLLECT_SAMPLE_REQ = 0x0122
    COLLECT_SAMPLE_RES = 0x0222
    # 采集停止
    COLLECT_STOP_REQ = 0x012F

    # 获取光源状态
    LIGHT_STATUS_REQ = 0x0130
    LIGHT_STATUS_RES = 0x0230
    # 获取激光状态
    LASER_STATUS_REQ = 0x0131
    LASER_STATUS_RES = 0x0231
    # 获取温度
    TEMPERATURE_REQ = 0x0132
    TEMPERATURE_RES = 0x0232
    # 获取湿度
    HUMIDITY_REQ = 0x0133
    HUMIDITY_RES = 0x0233

    # 打开光源
    TURN_ON_LIGHT = 0x0301
    # 关闭光源
    TURN_OFF_LIGHT = 0x0302
    # 打开激光
    TURN_ON_LASER = 0x0303
    # 关闭激光
    TURN_OFF_LASER = 0x0304

    # 设置旋转电机偏移量
    SET_ROTATE_OFFSET = 0x0310
    # 设置旋转电机目标位置
    SET_ROTATE_TARGET = 0x0311

    # 设置丝杆电机偏移量
    SET_SCREW_OFFSET = 0x0312
    # 设置丝杆电机目标位置
    SET_SCREW_TARGET = 0x0313

    # 设置PWM参数
    SET_PWM_PARAM = 0x0314

    # 设置硬件配置
    SET_HARDWARE_SETTING = 0x03F0
